import re
from ipaddress import ip_interface
from typing import Annotated, Any, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field

from api.models.keys import WireGuardKey

# wg-quick's rule for interface names.
INTERFACE_NAME_PATTERN = re.compile(r"^[a-zA-Z0-9_=+.-]{1,15}$")
# As wg parses it: "off" in any case, or a number, in hexadecimal only with a lowercase "0x".
FWMARK_PATTERN = re.compile(r"^((?i:off)|0x[0-9a-fA-F]+|[0-9]+)$")

NAME_DESCRIPTION = "Interface name, e.g. wg0."
STATUS_DESCRIPTION = (
    "'up' if the interface is running, or 'down' if it only has a .conf file. "
    "The runtime fields are only reported when it is up."
)
ADDRESS_DESCRIPTION = (
    "A comma-separated list of IP (v4 or v6) addresses (optionally with CIDR masks) to be assigned to the interface."
)
PRIVATE_KEY_DESCRIPTION = "A base64 private key generated by wg genkey. Write-only: it is never returned."
PUBLIC_KEY_DESCRIPTION = "A base64 public key calculated by wg pubkey from the private key."
LISTEN_PORT_DESCRIPTION = "A 16-bit port for listening. If not specified, or set to 0, chosen randomly."
FWMARK_DESCRIPTION = (
    "A 32-bit fwmark for outgoing packets. If set to 0 or 'off', this option is disabled. "
    "May be specified in hexadecimal by prepending '0x'. Reported as null when disabled."
)
NUM_PEERS_DESCRIPTION = "Number of peers configured on the interface."

# For secrets such as private keys: accepted, never returned.
WRITE_ONLY: dict[str, Any] = {"writeOnly": True}


def _check_name(value: str) -> str:
    if not INTERFACE_NAME_PATTERN.fullmatch(value):
        raise ValueError("Invalid interface name: expected 1 to 15 letters, digits or _=+.-")
    return value


def _check_address(value: str) -> str:
    for item in value.split(","):
        address = item.strip(" ")  # only spaces: a newline would start a new line in the .conf
        try:
            ip_interface(address)
        except ValueError:
            raise ValueError(f"Invalid address: {address}") from None
    return value


def _check_fwmark(value: str) -> str:
    if value.lower() != "off" and (
        not FWMARK_PATTERN.fullmatch(value) or int(value, 16 if value.startswith("0x") else 10) > 0xFFFFFFFF
    ):
        raise ValueError("Invalid fwmark: expected 'off' or a 32-bit number, in decimal or in hexadecimal with '0x'")
    return value


InterfaceName = Annotated[str, AfterValidator(_check_name)]
Address = Annotated[str, AfterValidator(_check_address)]
Fwmark = Annotated[str, AfterValidator(_check_fwmark)]


class Interface(BaseModel):
    """A WireGuard interface, as `wg show` reports it."""

    # Not validated: it comes from wg, and kernel names may have characters that wg-quick does not allow.
    name: str = Field(description=NAME_DESCRIPTION)
    status: Literal["up", "down"] = Field(description=STATUS_DESCRIPTION)
    public_key: str | None = Field(None, description=PUBLIC_KEY_DESCRIPTION)
    listen_port: int | None = Field(None, description=LISTEN_PORT_DESCRIPTION)
    fwmark: str | None = Field(None, description=FWMARK_DESCRIPTION)
    num_peers: int = Field(0, description=NUM_PEERS_DESCRIPTION)


class InterfaceUpdate(BaseModel):
    """Runtime settings applied with `wg set`. Omitted fields are left unchanged."""

    model_config = ConfigDict(extra="forbid")

    private_key: WireGuardKey | None = Field(None, description=PRIVATE_KEY_DESCRIPTION, json_schema_extra=WRITE_ONLY)
    listen_port: int | None = Field(None, ge=0, le=65535, description=LISTEN_PORT_DESCRIPTION)
    fwmark: Fwmark | None = Field(None, description=FWMARK_DESCRIPTION)


class InterfaceCreate(BaseModel):
    """A new interface: a minimal .conf with these settings, brought up with wg-quick."""

    # Only these fields: hooks such as PostUp would let API clients run commands as root.
    model_config = ConfigDict(extra="forbid")

    name: InterfaceName = Field(description=NAME_DESCRIPTION)
    address: Address = Field(description=ADDRESS_DESCRIPTION)
    private_key: WireGuardKey = Field(description=PRIVATE_KEY_DESCRIPTION, json_schema_extra=WRITE_ONLY)
    listen_port: int | None = Field(None, ge=0, le=65535, description=LISTEN_PORT_DESCRIPTION)
