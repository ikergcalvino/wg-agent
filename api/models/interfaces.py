from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from api.types import Address, Fwmark, InterfaceName, Port, WireGuardKey

NAME_DESCRIPTION = "Interface name, e.g. wg0."
STATUS_DESCRIPTION = (
    "'up' if the interface is running, or 'down' if it only has a .conf file. "
    "The runtime fields are only reported when it is up."
)
ADDRESS_DESCRIPTION = (
    "A comma-separated list of IP (v4 or v6) addresses (optionally with CIDR masks) to be assigned to the interface. "
    "Reported, with their masks, only when the interface is up."
)
PRIVATE_KEY_DESCRIPTION = "A base64 private key generated by wg genkey. Write-only: it is never returned."
PUBLIC_KEY_DESCRIPTION = "A base64 public key calculated by wg pubkey from the private key."
LISTEN_PORT_DESCRIPTION = "A 16-bit port for listening. If not specified, or set to 0, chosen randomly."
FWMARK_DESCRIPTION = (
    "A 32-bit fwmark for outgoing packets. If set to 0 or 'off', this option is disabled. "
    "May be specified in hexadecimal by prepending '0x'. Reported as null when disabled."
)
NUM_PEERS_DESCRIPTION = "Number of peers configured on the interface."


class Interface(BaseModel):
    """A WireGuard interface, as `wg show` reports it."""

    # Not validated: it comes from wg, and kernel names may have characters that wg-quick does not allow.
    name: str = Field(description=NAME_DESCRIPTION)
    status: Literal["up", "down"] = Field(description=STATUS_DESCRIPTION)
    address: str | None = Field(None, description=ADDRESS_DESCRIPTION)
    public_key: str | None = Field(None, description=PUBLIC_KEY_DESCRIPTION)
    listen_port: int | None = Field(None, description=LISTEN_PORT_DESCRIPTION)
    fwmark: str | None = Field(None, description=FWMARK_DESCRIPTION)
    num_peers: int | None = Field(None, description=NUM_PEERS_DESCRIPTION)


class InterfaceUpdate(BaseModel):
    """Runtime settings applied with `wg set`. Omitted fields are left unchanged."""

    model_config = ConfigDict(extra="forbid")

    private_key: WireGuardKey | None = Field(None, description=PRIVATE_KEY_DESCRIPTION)
    listen_port: Port | None = Field(None, description=LISTEN_PORT_DESCRIPTION)
    fwmark: Fwmark | None = Field(None, description=FWMARK_DESCRIPTION)


class InterfaceCreate(BaseModel):
    """A new interface: a minimal .conf with these settings, brought up with wg-quick."""

    # Only these fields: hooks such as PostUp would let API clients run commands as root.
    model_config = ConfigDict(extra="forbid")

    name: InterfaceName = Field(description=NAME_DESCRIPTION)
    address: Address = Field(description=ADDRESS_DESCRIPTION)
    private_key: WireGuardKey = Field(description=PRIVATE_KEY_DESCRIPTION)
    listen_port: Port | None = Field(None, description=LISTEN_PORT_DESCRIPTION)
